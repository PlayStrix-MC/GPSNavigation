package com.gpsnavigation.route;

/** Указатель маршрута: клиентский (пакетный) или запасной на сущности. */
public interface PointerHandle {

    /** Существует ли указатель (сущность могла выгрузиться вместе с чанком). */
    boolean isValid();

    void remove();

    /** Забыть указатель без отправки пакетов (клиент уже сам очистил сущности: смерть, смена мира). */
    default void forget() {
    }
}
